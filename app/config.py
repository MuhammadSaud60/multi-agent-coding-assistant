"""Central configuration for the multi-agent coding assistant.

Model selection and workspace location live here so no agent hardcodes them.

Environment variables:
    MACA_MODEL_PROVIDER  ollama (default) | gemini | openai | fake
    MACA_MODEL           model name. Defaults per provider
                         (ollama: llama3.2:3b, gemini: gemini-2.0-flash,
                         openai: gpt-4o-mini).
    MACA_WORKSPACE       directory the agents generate code into.
                         Default: <project root>/generated_project.
                         Relative values are resolved against the CWD,
                         the default is anchored to the project root so the
                         workspace does not move with the process CWD.
    MACA_FAKE_FILES_JSON optional JSON payload used by the "fake" provider
                         for the developer's structured output, shaped like
                         {"files": [{"path": ..., "content": ...}],
                          "entrypoint": ...}. Used by the offline smoke
                         test; see scripts/smoke_test.py.

The "fake" provider needs no server and no API key. It exists so the whole
graph can be exercised end to end in tests and CI.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()


def _sanitize_proxy_env() -> None:
    """Work around an import-time crash in the `ollama` package.

    ollama builds an httpx client at import time, and httpx raises
    InvalidURL when NO_PROXY contains bracketed IPv6 literals such as
    "[::1]" (common in sandboxed/CI environments). Dropping the IPv6
    entries from this process's copy of NO_PROXY avoids the crash; the
    plain "localhost"/"127.0.0.1" entries that local Ollama traffic
    relies on are kept.
    """
    for var in ("NO_PROXY", "no_proxy"):
        raw = os.environ.get(var)
        if raw and "[" in raw:
            kept = [
                entry
                for entry in (part.strip() for part in raw.split(","))
                if entry and "[" not in entry
            ]
            os.environ[var] = ",".join(kept)


_sanitize_proxy_env()

PROJECT_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_MODELS = {
    "ollama": "llama3.2:3b",
    "gemini": "gemini-2.0-flash",
    "openai": "gpt-4o-mini",
    "fake": "fake",
}


def get_workspace_root() -> Path:
    """Root directory that all generated code lives in."""
    raw = os.getenv("MACA_WORKSPACE", "").strip()
    if raw:
        return Path(raw).expanduser().resolve()
    return (PROJECT_ROOT / "generated_project").resolve()


def get_provider() -> str:
    return os.getenv("MACA_MODEL_PROVIDER", "ollama").strip().lower()


def get_model_name(provider: str | None = None) -> str:
    provider = provider or get_provider()
    return (
        os.getenv("MACA_MODEL", "").strip()
        or DEFAULT_MODELS.get(provider, DEFAULT_MODELS["ollama"])
    )


_FAKE_RESPONSES = {
    "supervisor": ["planner"],
    "planner": [
        "Plan (fake model): 1) Create main.py that prints a greeting. "
        "2) Run it to verify it executes."
    ],
    "debugger": ["The fake model does not apply fixes."],
    "generic": ["ok"],
}


def get_llm(role: str = "generic", temperature: float = 0):
    """Build the chat model for an agent role from the environment config."""
    provider = get_provider()
    model = get_model_name(provider)

    if provider == "fake":
        from langchain_core.language_models.fake_chat_models import (
            FakeListChatModel,
        )

        return FakeListChatModel(
            responses=_FAKE_RESPONSES.get(role, _FAKE_RESPONSES["generic"])
        )

    if provider == "ollama":
        from langchain_ollama import ChatOllama

        return ChatOllama(model=model, temperature=temperature)

    if provider == "gemini":
        from langchain_google_genai import ChatGoogleGenerativeAI

        return ChatGoogleGenerativeAI(model=model, temperature=temperature)

    if provider == "openai":
        from langchain_openai import ChatOpenAI

        return ChatOpenAI(model=model, temperature=temperature)

    raise ValueError(
        f"Unknown MACA_MODEL_PROVIDER: {provider!r} "
        "(expected one of: ollama, gemini, openai, fake)"
    )


_DEFAULT_FAKE_PAYLOAD = {
    "files": [
        {
            "path": "main.py",
            "content": (
                '"""Generated by the fake model for the offline smoke test."""'
                "\n\n"
                'print("Hello from the multi-agent coding assistant '
                '(fake model run).")\n'
            ),
        }
    ],
    "entrypoint": "main.py",
}


def get_structured_llm(schema):
    """Return an object whose .invoke(prompt) yields an instance of `schema`.

    Used by the developer agent. With the "fake" provider this returns a
    runnable that builds the schema from MACA_FAKE_FILES_JSON (or a small
    hello-world default), because FakeListChatModel does not implement
    with_structured_output.
    """
    if get_provider() == "fake":
        from langchain_core.runnables import RunnableLambda

        raw = os.getenv("MACA_FAKE_FILES_JSON", "").strip()
        payload = json.loads(raw) if raw else _DEFAULT_FAKE_PAYLOAD
        return RunnableLambda(lambda _prompt: schema(**payload))

    llm = get_llm("developer")
    return llm.with_structured_output(schema, method="json_schema")
